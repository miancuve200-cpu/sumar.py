# Programa para sumar dos números
# Ejecútalo y escribe los valores que quieras sumar

print("=== Calculadora de Sumas para Estudiantes ===")

# Pedir números al estudiante
num1 = float(input("Escribe el primer número: "))
num2 = float(input("Escribe el segundo número: "))

# Hacer la suma
resultado = num1 + num2

# Mostrar el resultado claro
print(f"\n✅ El resultado de la suma es: {num1} + {num2} = {resultado}")
